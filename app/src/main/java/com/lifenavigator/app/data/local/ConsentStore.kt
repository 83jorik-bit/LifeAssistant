/** Запись о данном согласии. */
data class ConsentRecord(
    val version: Int,
    val signedAtEpochSeconds: Long,
    /** Подпись в виде PNG, закодированного в Base64. */
    val signatureBase64: String
)

/**
 * Хранит факт согласия на устройстве. Когда появится сервер, эту же запись нужно
 * будет отправлять и хранить на стороне оператора — иначе доказать факт согласия
 * будет нечем.
 */
object ConsentStore {

    private val _consent = MutableStateFlow<ConsentRecord?>(null)
    val consent: StateFlow<ConsentRecord?> = _consent

    fun load(context: Context) {
        val prefs = prefs(context)
        val version = prefs.getInt(KEY_VERSION, 0)
        val signedAt = prefs.getLong(KEY_SIGNED_AT, 0L)
        val signature = prefs.getString(KEY_SIGNATURE, null)
        _consent.value = if (version > 0 && signedAt > 0 && signature != null) {
            ConsentRecord(version, signedAt, signature)
        } else {
            null
        }
    }

    fun save(context: Context, signatureBase64: String) {
        val record = ConsentRecord(
            version = ConsentText.VERSION,
            signedAtEpochSeconds = Instant.now().epochSecond,
            signatureBase64 = signatureBase64
        )
        prefs(context).edit()
            .putInt(KEY_VERSION, record.version)
            .putLong(KEY_SIGNED_AT, record.signedAtEpochSeconds)
            .putString(KEY_SIGNATURE, record.signatureBase64)
            .apply()
        _consent.value = record
    }

    fun revoke(context: Context) {
        prefs(context).edit().clear().apply()
        _consent.value = null
    }

    /** Согласие действительно, только если подписана текущая редакция текста. */
    fun isValid(): Boolean = _consent.value?.version == ConsentText.VERSION

    private fun prefs(context: Context) =
        context.getSharedPreferences("consent", Context.MODE_PRIVATE)

    private const val KEY_VERSION = "version"
    private const val KEY_SIGNED_AT = "signed_at"
    private const val KEY_SIGNATURE = "signature_png_base64"
}
